ALTER TABLE insumo ADD COLUMN localizacao VARCHAR(40);

-- Validade do que chegou. O saldo atual é atribuído aos lotes mais novos (o mais antigo sai primeiro),
-- então não é preciso informar de qual lote saiu cada venda.
CREATE TABLE insumo_validade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id   BIGINT         NOT NULL REFERENCES insumo(id) ON DELETE CASCADE,
    quantidade  NUMERIC(14,3)  NOT NULL CHECK (quantidade > 0),
    validade    DATE           NOT NULL,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por  VARCHAR(50)    NOT NULL
);

CREATE INDEX idx_insumo_validade_insumo ON insumo_validade (insumo_id);
